"""资产包管理：pack.json 清单 + sha256 校验 + Tier-0/1 两级检索 + zip 分发。

A pack is a self-contained unit of reusable assets::

    packs/<id>/
    ├── pack.json          # manifest (schema below)
    ├── module_gen.py      # optional generator for the pack's modules
    ├── modules/<category>/<name>.schem (+ .module.json)
    ├── styles/*.json      # optional material/style packs
    └── catalog.md        # Tier-0 compact catalog (generated by `scan`)
  previews/*.png     # optional preview images (indexed into pack.json)

Manifest schema::

    {
      "id": "modern-arch", "name": "...", "version": "1.0.0",
      "description": "...", "author": "...", "license": "MIT",
      "mc_versions": ["1.21.4"], "engine_requires": ">=0.2.0",
      "dependencies": {},
      "provides": {"modules": [...], "styles": [...], "generator": "..."},
      "previews": {"office_room": "previews/office_room.png"},
      "files": {"<rel>": "sha256:<hex>"},   # every file except pack.json
      "tags": [...]
    }

Commands:
  list        table of packs
  scan        rebuild packs/index.json, refresh every pack.json + catalog.md
  validate    manifest schema + files(sha256) + dependencies + previews
  catalog     generate Tier-0 compact catalog (per pack or all packs)
  search      Tier-1 structured search inside a pack (or all packs)
  export      build dist/<id>-<version>.zip for distribution
  import      install a pack zip (checksum-verified, dependency-checked)
  import-modules  batch-import structure files as modules (auto size/spec/dedupe)
  previews    render preview images for a pack's modules
"""
